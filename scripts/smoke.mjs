import { startDownload } from './ui-download.mjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, unlink, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
await mkdir('evidence', { recursive: true });
const root = await mkdtemp(resolve('evidence/runtime-smoke-'));
execFileSync('/opt/homebrew/bin/ffmpeg', ['-hide_banner', '-loglevel', 'error', '-n', '-f', 'lavfi', '-i',
  'testsrc2=size=640x360:rate=24:duration=3', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000:duration=3',
  '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-movflags', '+faststart', join(root, 'fixture.mp4')]);
execFileSync('/opt/homebrew/bin/ffmpeg', ['-hide_banner', '-loglevel', 'error', '-n', '-i', join(root, 'fixture.mp4'), '-vn', '-c:a', 'copy', join(root, 'fixture.m4a')]);
const env = { ...process.env, CLIPKEEP_TEST_MODE: '1', CLIPKEEP_TEST_ROOT: root };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.'], env });
const watchdog = setTimeout(() => { console.error('Test watchdog timeout'); app.process().kill('SIGKILL'); }, 90_000);
const checks = [];
const mark = name => { checks.push(name); console.log(`PASS ${name}`); };
let page;
const state = async () => page.evaluate(async () => (await window.desktop.snapshot()).value);
async function waitStatus(status) {
  for (let i = 0; i < 150; i++) {
    if ((await state()).job?.status === status) return;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  throw new Error(`Expected ${status}; got ${JSON.stringify(await state())}`);
}
try {
  page = await app.firstWindow();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.waitForLoadState('networkidle');
  await page.getByRole('heading', { name: '拾片 Clipkeep' }).waitFor();
  await page.waitForFunction(async () => (await window.desktop.snapshot()).value.tools.length === 4);
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  assert.equal(await page.evaluate(() => typeof window.process), 'undefined');
  const prefs = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences());
  assert.equal(prefs.sandbox, true); assert.equal(prefs.contextIsolation, true); assert.equal(prefs.nodeIntegration, false);
  mark('真实 Electron 启动，隔离与沙箱开启');
  await page.getByLabel('视频链接').fill('https://localhost/watch?v=abcdefghijk');
  await page.getByRole('button', { name: '读取视频' }).click();
  await page.getByRole('alert').filter({ hasText: 'HTTPS 视频链接' }).waitFor();
  mark('无效链接显示明确错误');
  await page.getByLabel('视频链接').fill('https://www.youtube.com/watch?v=abcdefghijk');
  await page.getByRole('button', { name: '读取视频' }).click();
  await page.getByRole('heading', { name: '一小段海风 · 本地测试影片' }).waitFor();
  assert.equal(await page.getByLabel('清晰度', { exact: true }).inputValue(), '137');
  await page.getByLabel('清晰度', { exact: true }).selectOption('136');
  await page.getByRole('button', { name: '更换目录' }).click();
  assert.equal((await state()).saveDirectory, root);
  mark('标题、时长、清晰度与目录选择');
  await page.getByRole('button', { name: '视频 + 音频 MP4 + M4A', exact: true }).click();
  await page.screenshot({ path: 'evidence/ui-ready.png', fullPage: true });
  await page.getByRole('button', { name: '开始下载' }).evaluate(button => { button.click(); button.click(); });
  await page.getByRole('button', { name: '取消任务', exact: true }).waitFor();
  const activeCard = page.locator('.task-card.running');
  await activeCard.getByText('更多操作', { exact: true }).click();
  assert.equal(await activeCard.getByRole('button', { name: '编辑设置', exact: true }).count(), 0);
  assert.equal(await activeCard.getByRole('button', { name: '移到队首', exact: true }).count(), 0);
  await page.screenshot({ path: 'evidence/ui-progress.png', fullPage: true });
  assert.equal((await readdir(root)).filter(name => name.startsWith('拾片-')).length, 1);
  await page.getByRole('button', { name: '取消任务', exact: true }).click();
  await waitStatus('cancelled');
  const cancelled = (await state()).job;
  assert.ok((await readdir(join(cancelled.directory, '.work'))).some(name => name.endsWith('.part')));
  mark('重复点击仅一个任务；取消保留 .part');
  await page.getByRole('tab', { name: '历史', exact: true }).click();
  await page.getByRole('button', { name: '重试任务' }).click();
  await page.getByRole('button', { name: '继续队列', exact: true }).click();
  await waitStatus('done');
  const done = (await state()).job;
  assert.equal(done.directory, cancelled.directory); assert.equal(done.outputs.length, 2);
  assert.equal(await readFile(join(root, 'download-count'), 'utf8'), '1');
  const mp4 = done.outputs.find(path => path.endsWith('.mp4'));
  const original = await readFile(mp4);
  mark('取消后重试复用目录，两份成果只下载一次');
  await page.getByRole('button', { name: '打开文件夹' }).first().click();
  mark('打开文件夹 IPC 成功');
  await page.screenshot({ path: 'evidence/ui-success.png', fullPage: true });
  await writeFile(join(root, 'fail-download'), '1');
  await startDownload(page);
  await waitStatus('failed');
  await page.screenshot({ path: 'evidence/ui-error.png', fullPage: true });
  await unlink(join(root, 'fail-download'));
  await page.getByRole('tab', { name: '历史', exact: true }).click();
  await page.getByRole('button', { name: '重试任务' }).click();
  await page.getByRole('button', { name: '继续队列', exact: true }).click();
  await waitStatus('done');
  assert.deepEqual(await readFile(mp4), original);
  mark('错误提示与错误重试通过，已有成果字节未改变');
  await writeFile(join(root, 'missing-tool'), '1');
  await page.getByRole('button', { name: '设置与帮助', exact: true }).click();
  await page.getByRole('button', { name: '重新检测' }).click();
  await page.getByText('缺失或无法启动', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '开始下载' }).isDisabled(), true);
  await unlink(join(root, 'missing-tool'));
  await page.getByRole('button', { name: '重新检测' }).click();
  await page.waitForFunction(async () => (await window.desktop.snapshot()).value.tools.every(tool => tool.ready));
  await page.keyboard.press('Escape');
  mark('工具缺失阻止下载，重新检测可恢复');
  await page.getByRole('button', { name: '纯音频 M4A', exact: true }).click();
  await startDownload(page); await waitStatus('running'); await waitStatus('done');
  assert.equal((await state()).job.outputs.length, 1); assert.ok((await state()).job.outputs[0].endsWith('.m4a'));
  await page.getByRole('button', { name: '带声视频 MP4', exact: true }).click();
  await startDownload(page); await waitStatus('running'); await waitStatus('done');
  assert.equal((await state()).job.outputs.length, 1); assert.ok((await state()).job.outputs[0].endsWith('.mp4'));
  mark('纯音频、带声 MP4 两种单独模式均通过');
  await page.getByText('登录与访问', { exact: true }).click();
  await page.getByText('隐私说明', { exact: true }).click();
  assert.equal(await page.getByRole('checkbox').isChecked(), false);
  assert.equal(await page.getByRole('checkbox').isDisabled(), true);
  const invalid = await page.evaluate(() => window.desktop.start({ mode: 'both', qualityId: '--exec=bad', useBrowser: false }));
  assert.equal(invalid.ok, false);
  assert.deepEqual(errors, []);
  mark('默认无登录态，测试模式禁用凭据，IPC 参数校验，零页面错误');
  await writeFile('evidence/ui-results.json', JSON.stringify({ passed: true, date: new Date().toISOString(), checks, root, errors }, null, 2));
} catch (error) { console.error(error); throw error; }
finally {
  await page?.evaluate(() => window.desktop.cancel()).catch(() => {});
  await app.close(); clearTimeout(watchdog);
}
